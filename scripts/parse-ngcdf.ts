/**
 * Parses NG-CDF Board project code lists (PDF) for Kipkelion West into
 * data/record/ngcdf-projects.ts.
 *
 *   npm run parse:ngcdf
 *
 * Requires `pdftotext` (poppler-utils). Source PDFs live in data/raw/ngcdf/
 * and are listed with their origin URLs in data/sources.ts (ids ngcdf-*).
 *
 * The PDFs carry no ward column. Ward is only set when the document text
 * names a ward explicitly; it is never guessed from a school's name.
 * Sector comes from the document's section heading where one exists;
 * otherwise it is inferred from keywords and marked `sectorSource: "inferred"`.
 */
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { findWard, inferSector, normaliseHeading } from "./ngcdf/classify";
import { parseLines, type RawRow } from "./ngcdf/rows";

const ROOT = path.resolve(__dirname, "..");
const RAW = path.join(ROOT, "data/raw/ngcdf");
const OUT = path.join(ROOT, "data/record/ngcdf-projects.ts");

const tidy = (s: string) => s.replace(/\s+/g, " ").trim();

type Doc = { fy: string; rows: RawRow[]; docTotals: number[] };

function read(file: string): Doc {
  const text = execFileSync("pdftotext", ["-layout", path.join(RAW, file), "-"], {
    encoding: "utf8",
  });
  const fy = file.replace(".pdf", "").replace("-", "/");
  return { fy, ...parseLines(text.split("\n")) };
}

function main() {
  const docs = readdirSync(RAW)
    .filter((f) => f.endsWith(".pdf"))
    .sort()
    .map(read);

  const projects = docs.flatMap((d) =>
    d.rows.map((r, i) => {
      const heading = r.heading ? normaliseHeading(r.heading) : null;
      const text = `${r.name} ${r.activity}`;
      return {
        id: `${d.fy.replace("/", "-")}-${String(i + 1).padStart(3, "0")}`,
        fy: d.fy,
        list: r.list,
        sn: r.sn,
        code: r.code || undefined,
        name: tidy(r.name),
        activity: tidy(r.activity),
        amount: r.amount,
        status: r.status,
        sector: heading ?? inferSector(r.name, r.activity),
        sectorSource: heading ? ("heading" as const) : ("inferred" as const),
        ward: findWard(text),
        sourceId: `ngcdf-${d.fy.replace("/", "-")}`,
      };
    }),
  );

  const summary = docs.map((d) => {
    const parsed = projects.filter((p) => p.fy === d.fy).reduce((s, p) => s + p.amount, 0);
    return { fy: d.fy, rows: d.rows.length, parsed: Math.round(parsed * 100) / 100, docTotals: d.docTotals };
  });
  console.table(summary);

  const banner = `// GENERATED by scripts/parse-ngcdf.ts — do not edit by hand.\n// Source: NG-CDF Board project code lists for Kipkelion West (see data/sources.ts, ids ngcdf-*).\n// These are APPROVED project proposals, not records of spending or completion.\n`;
  writeFileSync(
    OUT,
    `${banner}import type { NgcdfProject, NgcdfDocSummary } from "./ngcdf-types";\n\n` +
      `export const ngcdfDocs: NgcdfDocSummary[] = ${JSON.stringify(summary, null, 2)};\n\n` +
      `export const ngcdfProjects: NgcdfProject[] = ${JSON.stringify(projects, null, 2)};\n`,
  );
  console.log(`Wrote ${projects.length} projects → ${path.relative(ROOT, OUT)}`);
}

main();
