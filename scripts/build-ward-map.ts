/**
 * npm run build:wardmap → data/wards/geometry.ts
 *
 * Projects real IEBC ward boundaries (HDX "Kenya Elections" dataset, via
 * github.com/tigawanna/kenya_wards_geojson_data) to SVG paths:
 *  - the 4 Kipkelion West wards (detail map)
 *  - Kericho County's 6 constituencies (locator map)
 * Source files: data/raw/geo/*.geojson (EPSG:4326).
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { geoCentroid, geoMercator, geoPath, type GeoPermissibleObjects } from "d3-geo";

type Ring = [number, number][];
type Feature = { type: "Feature"; properties: Record<string, string | number>; geometry: { type: "Polygon" | "MultiPolygon"; coordinates: Ring[] | Ring[][] } };
type FC = { type: "FeatureCollection"; features: Feature[] };

const ROOT = path.resolve(__dirname, "..");
const read = (f: string) => JSON.parse(readFileSync(path.join(ROOT, "data/raw/geo", f), "utf8")) as FC;

/** d3-geo wants exterior rings clockwise (planar lon/lat: negative shoelace area). */
const area = (r: Ring) => r.reduce((s, [x1, y1], i) => { const [x2, y2] = r[(i + 1) % r.length]!; return s + (x1 * y2 - x2 * y1); }, 0) / 2;
const fixRing = (r: Ring, exterior: boolean) => ((area(r) > 0) === exterior ? [...r].reverse() : r);
const fixPoly = (p: Ring[]) => p.map((r, i) => fixRing(r, i === 0));
function rewind(fc: FC): FC {
  return { ...fc, features: fc.features.map((f) => ({ ...f, geometry: { ...f.geometry, coordinates: f.geometry.type === "Polygon" ? fixPoly(f.geometry.coordinates as Ring[]) : (f.geometry.coordinates as Ring[][]).map(fixPoly) } })) };
}

/** Round to 0.1px and drop points closer than MIN px to the last kept one (cheap simplification). */
const MIN = 1.5;
function tidy(d: string) {
  return d
    .split("Z")
    .filter(Boolean)
    .map((ring) => {
      const pts = [...ring.matchAll(/[ML](-?[\d.]+),(-?[\d.]+)/g)].map((m) => [Number(m[1]), Number(m[2])] as const);
      const kept: (readonly [number, number])[] = [];
      for (const p of pts) {
        const last = kept[kept.length - 1];
        if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) >= MIN) kept.push(p);
      }
      return kept.length > 2 ? "M" + kept.map(([x, y]) => `${Math.round(x * 10) / 10},${Math.round(y * 10) / 10}`).join("L") + "Z" : "";
    })
    .join("");
}

function project(fc: FC, width: number, height: number, pad: number) {
  const proj = geoMercator().fitExtent([[pad, pad], [width - pad, height - pad]], fc as unknown as GeoPermissibleObjects);
  const gp = geoPath(proj);
  return fc.features.map((f) => {
    const [cx, cy] = proj(geoCentroid(f as unknown as GeoPermissibleObjects))!;
    return { props: f.properties, d: tidy(gp(f as unknown as GeoPermissibleObjects) ?? ""), cx: Math.round(cx), cy: Math.round(cy) };
  });
}

const slug = (s: string) => s.toLowerCase().replace(/[^a-z]+/g, "-").replace(/^-|-$/g, "");
const wards = project(rewind(read("kipkelion-west-wards.geojson")), 600, 520, 16).map((w) => ({ slug: slug(String(w.props.ward_name)), code: String(w.props.ward_code), d: w.d, cx: w.cx, cy: w.cy }));
const constituencies = project(rewind(read("kericho-constituencies.geojson")), 240, 240, 6).map((c) => ({ slug: slug(String(c.props.constituency_name)), name: String(c.props.constituency_name), d: c.d }));

const out = `// GENERATED by scripts/build-ward-map.ts. Do not edit.
// Real IEBC ward boundaries (HDX Kenya Elections dataset, EPSG:4326), Mercator-projected.
export const WARD_VIEWBOX = "0 0 600 520";
export const LOCATOR_VIEWBOX = "0 0 240 240";
export const wardShapes = ${JSON.stringify(wards, null, 1)} as const;
export const kerichoConstituencies = ${JSON.stringify(constituencies, null, 1)} as const;
`;
writeFileSync(path.join(ROOT, "data/wards/geometry.ts"), out);
